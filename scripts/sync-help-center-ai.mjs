/**
 * Concatenates help-center/_ai/*.md into TS string exports for tutor + Studio agent prompts.
 * Run from repo root: npm run help-center:sync-ai
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const hc = process.env.HELP_CENTER_ROOT?.trim() || path.join(root, 'help-center')

function readRequired(rel) {
  const p = path.join(hc, rel)
  if (!fs.existsSync(p)) {
    console.error('[sync-help-center-ai] Missing file:', p)
    process.exit(1)
  }
  return fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').trimEnd()
}

function emitTs(name, literal, outfile) {
  const header =
    '/* eslint-disable */\n/**\n * AUTO-GENERATED by scripts/sync-help-center-ai.mjs — do not edit by hand.\n' +
    ' * Source of truth: help-center/_ai/*.md\n' +
    ' * Regenerate: `npm run help-center:sync-ai` from the repo root (or rely on Sudar Studio / Learn builds).\n' +
    ` * Generated at: ${new Date().toISOString()}\n */\n\n`
  fs.mkdirSync(path.dirname(outfile), { recursive: true })
  fs.writeFileSync(outfile, header + `export const ${name} = ${JSON.stringify(literal)}\n`, 'utf8')
  console.log('[sync-help-center-ai] Wrote', path.relative(root, outfile))
}

const studio = readRequired(path.join('_ai', 'studio-navigation.md'))
const learn = readRequired(path.join('_ai', 'learn-navigation.md'))

emitTs(
  'SUDAR_STUDIO_PLATFORM_KNOWLEDGE',
  studio,
  path.join(root, 'sudar-studio', 'src', 'lib', 'agent', 'platformKnowledge.generated.ts')
)
emitTs(
  'SUDAR_LEARN_PLATFORM_KNOWLEDGE',
  learn,
  path.join(root, 'sudar-learn', 'src', 'content', 'learnPlatformKnowledge.generated.ts')
)

/** Minimal YAML frontmatter parse (title, description, audience, category, order, marketing) for manifest only. */
function looseParseFrontmatter(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)
  if (!m) return {}
  const data = {}
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([a-zA-Z0-9_-]+):\s*(.*)$/)
    if (!kv) continue
    const k = kv[1]
    let v = kv[2].trim()
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1)
    }
    if (k === 'order') {
      const n = Number(v)
      data[k] = Number.isFinite(n) ? n : 999
    } else if (k === 'marketing') {
      data[k] = v === 'true' || v === true
    } else {
      data[k] = v
    }
  }
  return data
}

function walkArticleSlugs(absDir, relParts = []) {
  if (!fs.existsSync(absDir)) return []
  const out = []
  for (const entry of fs.readdirSync(absDir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue
    const full = path.join(absDir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walkArticleSlugs(full, [...relParts, entry.name]))
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      const base = entry.name.replace(/\.md$/i, '')
      out.push([...relParts, base].join('/'))
    }
  }
  return out
}

function writeHelpManifest() {
  const articlesRoot = path.join(hc, 'articles')
  const slugs = walkArticleSlugs(articlesRoot).sort((a, b) => a.localeCompare(b))
  const articles = []
  for (const slug of slugs) {
    const fp = path.join(articlesRoot, ...slug.split('/')) + '.md'
    if (!fs.existsSync(fp)) continue
    const raw = fs.readFileSync(fp, 'utf8').replace(/\r\n/g, '\n')
    const data = looseParseFrontmatter(raw)
    articles.push({
      slug,
      title: data.title || slug,
      description: data.description || null,
      audience: data.audience || 'both',
      category: data.category || 'start-here',
      order: typeof data.order === 'number' ? data.order : 999,
      marketing: Boolean(data.marketing === true || data.marketing === 'true'),
    })
  }
  const manifestDir = path.join(hc, 'meta')
  fs.mkdirSync(manifestDir, { recursive: true })
  const outPath = path.join(manifestDir, 'manifest.json')
  fs.writeFileSync(
    outPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        articles,
      },
      null,
      2
    ) + '\n',
    'utf8'
  )
  console.log('[sync-help-center-ai] Wrote', path.relative(root, outPath))
}

writeHelpManifest()
